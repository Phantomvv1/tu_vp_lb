n = int(input("Въведете номер на ден от 1 до 7: "))

if n == 1:
    print("Денят с номер", n, "е понеделник")
elif n == 2:
    print("Денят с номер", n, "е вторник")
elif n == 3:
    print("Денят с номер", n, "е сряда")
elif n == 4:
    print("Денят с номер", n, "е четвъртък")
elif n == 5:
    print("Денят с номер", n, "е петък")
elif n == 6:
    print("Денят с номер", n, "е събота")
elif n == 7:
    print("Денят с номер", n, "е неделя")
else:
    print("Невалиден номер:", n)
